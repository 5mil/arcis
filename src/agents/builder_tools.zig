/// Register all builder tools into a ToolRegistry.
pub fn registerBuilderTools(registry: *ToolRegistry) !void {
    try registry.register(.{ .name = "create_project", .description = "Create a new project scaffold. Args: name, template (vite-react|html)", .handler = toolCreateProject });
    try registry.register(.{ .name = "write_file", .description = "Write content to a file inside a project. Args: project, path, content", .handler = toolWriteFile });
    try registry.register(.{ .name = "read_file", .description = "Read a file from a project. Args: project, path", .handler = toolReadFile });
    try registry.register(.{ .name = "list_files", .description = "List files/directories in a project path. Args: project, path (optional)", .handler = toolListFiles });
    try registry.register(.{ .name = "run_command", .description = "Run a whitelisted command (npm install, npm run dev, etc) inside the project. Args: project, command", .handler = toolRunCommand });
    try registry.register(.{ .name = "start_preview", .description = "Start the dev server for a project and return the local URL. Args: project, port (optional)", .handler = toolStartPreview });
    try registry.register(.{ .name = "stop_preview", .description = "Stop a running preview. Args: project", .handler = toolStopPreview });
}

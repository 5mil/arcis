//! builder_tools.zig — File-system and process tools for the Arcis Builder agent
//! These tools let the ReAct agent scaffold and refine full web apps from natural language.
//!
//! Safety rules:
//! - All paths are resolved under a fixed projects root (default: ./arcis-projects)
//! - Path traversal ("..") and absolute paths are rejected
//! - run_command is restricted to a small whitelist of safe commands inside the project dir

const std = @import("std");
const Allocator = std.mem.Allocator;
const Tool = @import("tool.zig").Tool;
const ToolRegistry = @import("tool.zig").ToolRegistry;

// ---------------------------------------------------------------------------
// Configuration
// ---------------------------------------------------------------------------

/// Root directory where all generated projects live.
pub var projects_root: []const u8 = "arcis-projects";

/// Simple in-memory map of running preview processes (project_name → pid).
/// Not persisted across restarts.
var preview_pids: ?std.StringHashMap(std.process.Child) = null;

fn ensurePreviewMap(allocator: Allocator) !*std.StringHashMap(std.process.Child) {
    if (preview_pids == null) {
        preview_pids = std.StringHashMap(std.process.Child).init(allocator);
    }
    return &preview_pids.?;
}

// ---------------------------------------------------------------------------
// Path helpers (security critical)
// ---------------------------------------------------------------------------

/// Reject path traversal and absolute paths. Returns cleaned relative path or error.
fn sanitizeRelPath(path: []const u8) ![]const u8 {
    if (path.len == 0) return error.EmptyPath;
    if (std.mem.startsWith(u8, path, "/") or std.mem.startsWith(u8, path, "\\")) {
        return error.AbsolutePathRejected;
    }
    if (std.mem.indexOf(u8, path, "..") != null) {
        return error.PathTraversalRejected;
    }
    // Strip leading "./"
    if (std.mem.startsWith(u8, path, "./")) return path[2..];
    return path;
}

/// Build full path: projects_root / project / rel_path
fn fullPath(allocator: Allocator, project: []const u8, rel: []const u8) ![]u8 {
    const clean_proj = try sanitizeRelPath(project);
    const clean_rel = if (rel.len == 0) "" else try sanitizeRelPath(rel);
    if (clean_rel.len == 0) {
        return std.fmt.allocPrint(allocator, "{s}/{s}", .{ projects_root, clean_proj });
    }
    return std.fmt.allocPrint(allocator, "{s}/{s}/{s}", .{ projects_root, clean_proj, clean_rel });
}

// ---------------------------------------------------------------------------
// Minimal JSON string extractor (same style as handlers.zig)
// ---------------------------------------------------------------------------

fn jsonGetString(body: []const u8, key: []const u8) ?[]const u8 {
    var needle_buf: [64]u8 = undefined;
    const needle = std.fmt.bufPrint(&needle_buf, "\"{s}\":\"", .{key}) catch return null;
    const start = std.mem.indexOf(u8, body, needle) orelse return null;
    const val_start = start + needle.len;
    // Handle escaped quotes naively: stop at first unescaped "
    var i = val_start;
    while (i < body.len) : (i += 1) {
        if (body[i] == '"' and (i == val_start or body[i - 1] != '\\')) {
            return body[val_start..i];
        }
    }
    return null;
}

